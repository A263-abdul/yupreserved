-- ════════════════════════════════════════════════════════════════════════════
--  02_tables.sql  ·  The 15 base tables of YupReserved
--  Syllabus: Relational model · Keys · Integrity · ER → relational mapping
--
--  Naming convention for constraints (so error messages explain themselves):
--      pk_<table>            primary key
--      uq_<table>_<cols>     alternate (candidate) key
--      fk_<child>_<parent>   foreign key
--      ck_<table>_<rule>     CHECK constraint
--      ex_<table>_<rule>     EXCLUDE constraint
--
--  Groups:   GEOGRAPHY   states · cities · landmarks
--            PROPERTY    hotels · hotel_landmarks · amenities · hotel_amenities
--            INVENTORY   room_types · rooms · seasons
--            CUSTOMER    guests
--            BOOKING     bookings · booking_rooms · payments · reviews
-- ════════════════════════════════════════════════════════════════════════════


-- ───────────────────────────── GEOGRAPHY ───────────────────────────────────

-- (1) states — natural key: the 2-letter state / UT code
CREATE TABLE states (
    state_code          char(2)      CONSTRAINT pk_states PRIMARY KEY,
    state_name          varchar(60)  NOT NULL CONSTRAINT uq_states_name UNIQUE,
    region              region_t     NOT NULL,
    is_union_territory  boolean      NOT NULL DEFAULT false,
    CONSTRAINT ck_states_code_format CHECK (state_code ~ '^[A-Z]{2}$')
);

-- (2) cities — surrogate key; (city_name, state_code) is the candidate key
--     because two states can have a city with the same name (Aurangabad: MH & BR)
CREATE TABLE cities (
    city_id     integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_cities PRIMARY KEY,
    city_name   varchar(80)  NOT NULL,
    state_code  char(2)      NOT NULL
                CONSTRAINT fk_cities_states REFERENCES states (state_code)
                ON UPDATE CASCADE ON DELETE RESTRICT,
    latitude    lat_deg,
    longitude   lon_deg,
    is_metro    boolean      NOT NULL DEFAULT false,
    tier        smallint     NOT NULL DEFAULT 3,
    -- free-licence photo from Wikimedia Commons (hot-linked, credited)
    photo_url     varchar(500),
    photo_url_hd  varchar(500),
    photo_credit  varchar(250),
    CONSTRAINT uq_cities_name_state  UNIQUE (city_name, state_code),
    CONSTRAINT ck_cities_photo       CHECK (photo_url IS NULL OR (photo_url ~ '^https://' AND photo_credit IS NOT NULL)),
    CONSTRAINT ck_cities_tier        CHECK (tier BETWEEN 1 AND 3),
    CONSTRAINT ck_cities_metro_tier  CHECK (NOT is_metro OR tier = 1)
);

-- (3) landmarks — places guests search by ("near Gateway of India")
CREATE TABLE landmarks (
    landmark_id    integer              GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_landmarks PRIMARY KEY,
    city_id        integer              NOT NULL
                   CONSTRAINT fk_landmarks_cities REFERENCES cities (city_id) ON DELETE CASCADE,
    landmark_name  varchar(120)         NOT NULL,
    category       landmark_category_t  NOT NULL DEFAULT 'LANDMARK',
    latitude       lat_deg,
    longitude      lon_deg,
    photo_url      varchar(500),
    photo_url_hd   varchar(500),
    photo_credit   varchar(250),
    CONSTRAINT uq_landmarks_city_name UNIQUE (city_id, landmark_name),
    CONSTRAINT ck_landmarks_photo     CHECK (photo_url IS NULL OR (photo_url ~ '^https://' AND photo_credit IS NOT NULL)),
    -- either both coordinates are known or neither is
    CONSTRAINT ck_landmarks_coords CHECK ((latitude IS NULL) = (longitude IS NULL))
);


-- ───────────────────────────── PROPERTY ────────────────────────────────────

-- (4) hotels — one row per property (real Goibibo listing or YupReserved original)
CREATE TABLE hotels (
    hotel_id        integer           GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_hotels PRIMARY KEY,
    source_ref      varchar(40)       NOT NULL CONSTRAINT uq_hotels_source_ref UNIQUE,
    source          listing_source_t  NOT NULL,
    hotel_name      varchar(120)      NOT NULL,
    property_type   property_type_t   NOT NULL,
    star_rating     smallint          NOT NULL DEFAULT 0,
    city_id         integer           NOT NULL
                    CONSTRAINT fk_hotels_cities REFERENCES cities (city_id) ON DELETE RESTRICT,
    locality        varchar(120),
    address         varchar(400)      NOT NULL,
    latitude        lat_deg           NOT NULL,
    longitude       lon_deg           NOT NULL,
    tagline         varchar(160),
    description     text              NOT NULL,
    check_in_time   time              NOT NULL DEFAULT '12:00',
    check_out_time  time              NOT NULL DEFAULT '11:00',
    is_signature    boolean           NOT NULL DEFAULT false,
    -- derived attributes, maintained by trigger trg_reviews_rollup (see 04_triggers.sql)
    avg_rating      numeric(2,1),
    review_count    integer           NOT NULL DEFAULT 0,
    -- full-text search document (Unit 5: digital libraries / information retrieval)
    search_doc      tsvector GENERATED ALWAYS AS (
                        setweight(to_tsvector('english', coalesce(hotel_name, '')), 'A') ||
                        setweight(to_tsvector('english', coalesce(locality, '') || ' ' || coalesce(tagline, '')), 'B') ||
                        setweight(to_tsvector('english', description), 'C')
                    ) STORED,
    CONSTRAINT ck_hotels_star         CHECK (star_rating BETWEEN 0 AND 5),
    CONSTRAINT ck_hotels_in_india     CHECK (latitude BETWEEN 6 AND 37.5 AND longitude BETWEEN 68 AND 97.5),
    CONSTRAINT ck_hotels_signature    CHECK (is_signature = (source = 'YUPRESERVED')),
    CONSTRAINT ck_hotels_rating_range CHECK (avg_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_hotels_rating_count CHECK (review_count >= 0 AND (avg_rating IS NULL) = (review_count = 0))
);

-- (5) hotel_landmarks — M:N between hotels and landmarks
CREATE TABLE hotel_landmarks (
    hotel_id     integer       NOT NULL
                 CONSTRAINT fk_hotel_landmarks_hotels REFERENCES hotels (hotel_id) ON DELETE CASCADE,
    landmark_id  integer       NOT NULL
                 CONSTRAINT fk_hotel_landmarks_landmarks REFERENCES landmarks (landmark_id) ON DELETE CASCADE,
    distance_km  numeric(5,2),               -- NULL = listed as nearby, distance unknown
    CONSTRAINT pk_hotel_landmarks PRIMARY KEY (hotel_id, landmark_id),
    CONSTRAINT ck_hotel_landmarks_distance CHECK (distance_km >= 0 AND distance_km < 100)
);

-- (6) amenities — controlled vocabulary (cleaned from 356 raw labels to 52)
CREATE TABLE amenities (
    amenity_id    smallint            GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_amenities PRIMARY KEY,
    amenity_name  varchar(60)         NOT NULL CONSTRAINT uq_amenities_name UNIQUE,
    category      amenity_category_t  NOT NULL
);

-- (7) hotel_amenities — the multivalued attribute "facilities" made atomic (1NF)
CREATE TABLE hotel_amenities (
    hotel_id    integer   NOT NULL
                CONSTRAINT fk_hotel_amenities_hotels REFERENCES hotels (hotel_id) ON DELETE CASCADE,
    amenity_id  smallint  NOT NULL
                CONSTRAINT fk_hotel_amenities_amenities REFERENCES amenities (amenity_id) ON DELETE RESTRICT,
    CONSTRAINT pk_hotel_amenities PRIMARY KEY (hotel_id, amenity_id)
);


-- ───────────────────────────── INVENTORY ───────────────────────────────────

-- (8) room_types — what a hotel sells ("Deluxe Room", "Lake Suite")
CREATE TABLE room_types (
    room_type_id  integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_room_types PRIMARY KEY,
    hotel_id      integer      NOT NULL
                  CONSTRAINT fk_room_types_hotels REFERENCES hotels (hotel_id) ON DELETE CASCADE,
    type_name     varchar(60)  NOT NULL,
    bed_type      bed_type_t   NOT NULL,
    max_adults    smallint     NOT NULL,
    max_children  smallint     NOT NULL DEFAULT 0,
    area_sqft     smallint     NOT NULL,
    base_price    rupees       NOT NULL,     -- list price per night, before season & tax
    CONSTRAINT uq_room_types_hotel_name UNIQUE (hotel_id, type_name),
    -- superkey that rooms can reference, so a room can never point at another hotel's type
    CONSTRAINT uq_room_types_id_hotel   UNIQUE (room_type_id, hotel_id),
    CONSTRAINT ck_room_types_adults     CHECK (max_adults BETWEEN 1 AND 6),
    CONSTRAINT ck_room_types_children   CHECK (max_children BETWEEN 0 AND 4),
    CONSTRAINT ck_room_types_area       CHECK (area_sqft BETWEEN 50 AND 5000),
    CONSTRAINT ck_room_types_price      CHECK (base_price BETWEEN 299 AND 500000)
);

-- (9) rooms — physical rooms. Conceptually a WEAK entity of hotels:
--     room_number is only unique inside its hotel (partial key).
--     Candidate keys: {room_id} and {hotel_id, room_number}.
CREATE TABLE rooms (
    room_id       integer     GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_rooms PRIMARY KEY,
    hotel_id      integer     NOT NULL,
    room_number   varchar(8)  NOT NULL,
    room_type_id  integer     NOT NULL,
    floor_no      smallint,
    is_active     boolean     NOT NULL DEFAULT true,     -- false = under maintenance
    CONSTRAINT uq_rooms_hotel_number UNIQUE (hotel_id, room_number),
    -- composite FK: (room_type_id, hotel_id) must exist together in room_types
    CONSTRAINT fk_rooms_room_types FOREIGN KEY (room_type_id, hotel_id)
               REFERENCES room_types (room_type_id, hotel_id) ON DELETE CASCADE,
    CONSTRAINT ck_rooms_floor CHECK (floor_no BETWEEN 0 AND 60)
);

-- (10) seasons — festival & holiday pricing calendar
CREATE TABLE seasons (
    season_id    smallint      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_seasons PRIMARY KEY,
    season_name  varchar(60)   NOT NULL CONSTRAINT uq_seasons_name UNIQUE,
    start_date   date          NOT NULL,
    end_date     date          NOT NULL,
    multiplier   numeric(3,2)  NOT NULL,
    notes        varchar(120),
    CONSTRAINT ck_seasons_dates      CHECK (end_date >= start_date),
    CONSTRAINT ck_seasons_multiplier CHECK (multiplier BETWEEN 0.50 AND 3.00),
    -- no two seasons may overlap, so every night has at most one season price
    CONSTRAINT ex_seasons_no_overlap EXCLUDE USING gist
               (daterange(start_date, end_date, '[]') WITH &&)
);


-- ───────────────────────────── CUSTOMER ────────────────────────────────────

-- (11) guests — people who book. Three candidate keys besides guest_id:
--      phone, email and (id_type, id_number).
CREATE TABLE guests (
    guest_id       integer        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_guests PRIMARY KEY,
    first_name     varchar(40)    NOT NULL,
    last_name      varchar(40)    NOT NULL,
    phone          indian_mobile  NOT NULL CONSTRAINT uq_guests_phone UNIQUE,
    email          email_address  NOT NULL CONSTRAINT uq_guests_email UNIQUE,
    date_of_birth  date           NOT NULL,
    id_type        id_document_t  NOT NULL,
    id_number      varchar(20)    NOT NULL,
    home_city_id   integer
                   CONSTRAINT fk_guests_cities REFERENCES cities (city_id) ON DELETE SET NULL,
    -- self-referencing FK (recursive relationship "refers")
    referred_by    integer
                   CONSTRAINT fk_guests_referrer REFERENCES guests (guest_id) ON DELETE SET NULL,
    created_at     timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT uq_guests_id_document UNIQUE (id_type, id_number),
    CONSTRAINT ck_guests_adult       CHECK (date_of_birth <= (created_at AT TIME ZONE 'Asia/Kolkata')::date - INTERVAL '18 years'),
    CONSTRAINT ck_guests_not_self    CHECK (referred_by <> guest_id)
);


-- ───────────────────────────── BOOKING ─────────────────────────────────────

-- (12) bookings — one reservation at one hotel for one date range
CREATE TABLE bookings (
    booking_id       integer           GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_bookings PRIMARY KEY,
    booking_ref      char(8)           NOT NULL CONSTRAINT uq_bookings_ref UNIQUE,   -- set by trigger
    guest_id         integer           NOT NULL
                     CONSTRAINT fk_bookings_guests REFERENCES guests (guest_id) ON DELETE RESTRICT,
    hotel_id         integer           NOT NULL
                     CONSTRAINT fk_bookings_hotels REFERENCES hotels (hotel_id) ON DELETE RESTRICT,
    check_in         date              NOT NULL,
    check_out        date              NOT NULL,
    nights           smallint          GENERATED ALWAYS AS (check_out - check_in) STORED,
    adults           smallint          NOT NULL DEFAULT 1,
    children         smallint          NOT NULL DEFAULT 0,
    status           booking_status_t  NOT NULL DEFAULT 'PENDING',
    special_request  varchar(200),
    booked_at        timestamptz       NOT NULL DEFAULT now(),
    cancelled_at     timestamptz,
    CONSTRAINT ck_bookings_ref_format CHECK (booking_ref ~ '^YR[A-Z0-9]{6}$'),
    CONSTRAINT ck_bookings_dates      CHECK (check_out > check_in),
    CONSTRAINT ck_bookings_max_stay   CHECK (check_out - check_in <= 30),
    CONSTRAINT ck_bookings_guests     CHECK (adults >= 1 AND children >= 0 AND adults + children <= 24),
    CONSTRAINT ck_bookings_booked_before_arrival
               CHECK ((booked_at AT TIME ZONE 'Asia/Kolkata')::date <= check_in),
    CONSTRAINT ck_bookings_cancel_state
               CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL)),
    CONSTRAINT ck_bookings_cancel_after_booking CHECK (cancelled_at >= booked_at)
);

-- (13) booking_rooms — which physical rooms a booking holds (M:N bookings ↔ rooms)
--      The price is stored because it is a fact agreed at booking time:
--      later changes to base_price or seasons must not rewrite history.
CREATE TABLE booking_rooms (
    booking_id     integer  NOT NULL
                   CONSTRAINT fk_booking_rooms_bookings REFERENCES bookings (booking_id) ON DELETE CASCADE,
    room_id        integer  NOT NULL
                   CONSTRAINT fk_booking_rooms_rooms REFERENCES rooms (room_id) ON DELETE RESTRICT,
    room_subtotal  rupees   NOT NULL,       -- sum of nightly rates for this room, before tax
    room_tax       rupees   NOT NULL,       -- GST on those nights
    CONSTRAINT pk_booking_rooms PRIMARY KEY (booking_id, room_id),
    CONSTRAINT ck_booking_rooms_amount CHECK (room_subtotal > 0)
);

-- (14) payments — every money movement (charges and refunds, successful or not)
CREATE TABLE payments (
    payment_id   integer           GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_payments PRIMARY KEY,
    booking_id   integer           NOT NULL
                 CONSTRAINT fk_payments_bookings REFERENCES bookings (booking_id) ON DELETE RESTRICT,
    kind         payment_kind_t    NOT NULL DEFAULT 'CHARGE',
    method       payment_method_t  NOT NULL,
    status       payment_status_t  NOT NULL DEFAULT 'PENDING',
    amount       rupees            NOT NULL,
    upi_vpa      varchar(60),
    card_last4   char(4),
    gateway_ref  varchar(24)       NOT NULL CONSTRAINT uq_payments_gateway_ref UNIQUE,
    created_at   timestamptz       NOT NULL DEFAULT now(),
    CONSTRAINT ck_payments_amount   CHECK (amount > 0),
    CONSTRAINT ck_payments_upi      CHECK (upi_vpa IS NULL OR (method = 'UPI' AND upi_vpa ~ '^[a-z0-9._-]{2,}@[a-z]{2,}$')),
    CONSTRAINT ck_payments_card     CHECK (card_last4 IS NULL OR (method = 'CARD' AND card_last4 ~ '^[0-9]{4}$')),
    CONSTRAINT ck_payments_upi_vpa_required CHECK (method <> 'UPI' OR upi_vpa IS NOT NULL)
);

-- (15) reviews — at most one review per completed stay (1:1 with bookings)
CREATE TABLE reviews (
    review_id   integer       GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_reviews PRIMARY KEY,
    booking_id  integer       NOT NULL
                CONSTRAINT uq_reviews_booking UNIQUE
                CONSTRAINT fk_reviews_bookings REFERENCES bookings (booking_id) ON DELETE CASCADE,
    rating      smallint      NOT NULL,
    title       varchar(100)  NOT NULL,
    body        text,
    created_at  timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);
